def next_code(session, ref: str) -> str:
    m = re.search(r"(\d{4})/(\d+)", ref or "")
    base = f"KB-{m.group(1)}-{m.group(2)}" if m else f"KB-{dt.date.today().year}-{session.query(KnowledgeEntry).count() + 1:03d}"
    code, n = base, 2
    while session.query(KnowledgeEntry).filter_by(code=code).first():
        code, n = f"{base}-{n}", n + 1
    return code


def _move_into_kb(token: str, ref: str, original: str) -> tuple[str, bool]:
    src = staged_path(token)
    if src is None:
        return "", False
    folder = config.KNOWLEDGE_DIR / UPLOAD_FOLDER
    folder.mkdir(parents=True, exist_ok=True)
    name = kb_filename(ref, original)
    dest = folder / name
    if dest.exists():
        if dest.read_bytes() == src.read_bytes():
            src.unlink(missing_ok=True)
            return f"{UPLOAD_FOLDER}/{name}", False
        dest = folder / f"{Path(name).stem}_{token[:4]}.pdf"
    shutil.move(str(src), str(dest))
    return f"{UPLOAD_FOLDER}/{dest.name}", True


def _reindex_corpus() -> None:
    from . import rag
    if rag.CORPUS.enabled():
        threading.Thread(target=rag.CORPUS.ensure, kwargs={"rebuild": True}, name="kb-reindex", daemon=True).start()


def publish(session, d: dict, actor: str, token: str = "", original_name: str = "") -> KnowledgeEntry:
    from . import monitor
    source_path, uploaded = _move_into_kb(token, d.get("ref", ""), original_name) if token else ("", False)
    rule = d.get("rule") or {}
    e = KnowledgeEntry(code=next_code(session, d.get("ref", "")), kind=d.get("kind") or "implementing",
                       ref=d.get("ref", ""), binding=bool(d.get("binding", True)), title=d["title"],
                       title_zh=d.get("title_zh", ""), text=d.get("text", ""), text_zh=d.get("text_zh", ""),
                       source_path=source_path or d.get("source_path", ""), uploaded_file=uploaded,
                       page=int(d.get("page") or 0), applies_from=d.get("applies_from", ""), status="active",
                       created_by=actor)
    e.articles, e.items, e.rule = d.get("articles", []), d.get("items", []), rule
    pub = _iso(d.get("published")) or dt.date.today()
    cond_en = "; ".join(c["en"] for c in rule.get("conditions", []))
    cond_zh = "；".join((c.get("zh") or c["en"]) for c in rule.get("conditions", []))
    u = RegUpdate(code=monitor.next_code(session), kind=e.kind, status="published", binding=e.binding,
                  severity="high" if rule else "medium", reference=e.ref, published=pub,
                  date_label=f"OJ {pub:%d %b %Y}" + (f" · in force {e.applies_from}" if e.applies_from else ""),
                  effective=_iso(e.applies_from), title=e.ref + (" — " + e.title if e.title else ""),
                  title_zh=e.ref + (" —— " + e.title_zh if e.title_zh else ""), summary=e.text, summary_zh=e.text_zh,
                  impact=d.get("impact", ""), impact_zh=d.get("impact_zh", ""),
                  evidence_change=("Conditions to evidence: " + cond_en) if cond_en else "",
                  evidence_change_zh=("须证明的条件：" + cond_zh) if cond_zh else "", source_path=e.source_path,
                  articles=e.articles, items=e.items, origin="manual", reviewed=True,
                  created_by=f"{actor} (manual knowledge update)")
    session.add(u)
    session.flush()
    e.update_id = u.id
    session.add(e)
    session.flush()
    log(session, f"knowledge base updated {e.code}", actor, comment=f"{e.ref} — {e.title}")
    refresh(session)
    rerun(session, e, actor, "published")
    if uploaded:
        _reindex_corpus()
    return e


def set_status(session, e: KnowledgeEntry, status: str, actor: str) -> dict:
    e.status, e.changed_at = status, now()
    session.flush()
    log(session, f"knowledge entry {e.code} {status}", actor, comment=e.ref)
    refresh(session)
    return rerun(session, e, actor, "withdrawn" if status == "withdrawn" else "re-activated")


def _key_checks(checks: list[dict]) -> list[dict]:
    return [{"desc": c["desc"], "desc_zh": c.get("desc_zh", ""), "ok": c["ok"], "msg": c.get("msg", ""),
             "msg_zh": c.get("msg_zh", "")} for c in checks or []]


def rerun(session, e: KnowledgeEntry, actor: str, reason: str) -> dict:
    """Re-run the AI pre-review on every open submission the entry touches; record before → after."""
    from . import ai_review
    rows = []
    items = list(e.items or [])
    if items:
        subs = session.query(Submission).filter(Submission.item_id.in_(items)).all()
        for s in subs:
            if s.status not in ("submitted", "ai_reviewed") or s.na_requested:
                continue
            p = s.project
            ev = [x for x in p.evidence if x.item_id == s.item_id and x.unit_id in (s.unit_id, None)]
            before_v, before_c = s.ai_verdict, _key_checks(s.ai_checks)
            ai_review.apply(s, p, s.unit, ev)
            after_c = _key_checks(s.ai_checks)
            seen = {(c["desc"], c["ok"], c["msg"]) for c in before_c}
            diff = [c for c in after_c if (c["desc"], c["ok"], c["msg"]) not in seen]
            gone = [c for c in before_c if (c["desc"], c["ok"], c["msg"]) not in
                    {(x["desc"], x["ok"], x["msg"]) for x in after_c}]
            rows.append({"sub_id": s.id, "project_id": p.id, "project": p.code, "client": p.client.name,
                         "unit": s.unit.code if s.unit else "", "unit_name": s.unit.name if s.unit else "",
                         "item": s.item_id, "before": before_v, "after": s.ai_verdict,
                         "changed": before_v != s.ai_verdict or bool(diff),
                         "new_checks": diff[:8], "old_checks": gone[:4]})
            if before_v != s.ai_verdict:
                log(session, "AI pre-review re-run after knowledge update", actor, p.id, s.unit_id, s.item_id,
                    f"{e.code} {reason}: {before_v} → {s.ai_verdict}")
    rows.sort(key=lambda r: (not r["changed"], r["project"], r["unit"], r["item"]))
    res = {"at": now().strftime("%d %b %Y %H:%M"), "reason": reason, "by": actor, "rows": rows,
           "changed": sum(1 for r in rows if r["changed"])}
    history = (e.rerun or {}).get("history", [])
    res["history"] = (history + [{k: res[k] for k in ("at", "reason", "by", "changed")}])[-10:]
    e.rerun = res
    return res


def entry_for_update(session, update_id: int) -> KnowledgeEntry | None:
    return session.query(KnowledgeEntry).filter_by(update_id=update_id).first()


def cleanup_for_reset() -> int:
    """Demo reset: remove the act files this feature wrote into the knowledge base and the staging area."""
    n = 0
    try:
        with SessionLocal() as s:
            for e in s.query(KnowledgeEntry).filter_by(uploaded_file=True):
                p = (config.KNOWLEDGE_DIR / e.source_path).resolve()
                if e.source_path and config.KNOWLEDGE_DIR.resolve() in p.parents and p.exists():
                    p.unlink()
                    n += 1
    except Exception:
        pass
    shutil.rmtree(STAGING_DIR, ignore_errors=True)
    if n:
        _reindex_corpus()
    return n
