UPLOAD_FOLDER = "01_PPWR and related regulation and act"
STAGING_DIR = config.DATA_DIR / "kb_staging"
DRAFTS_PATH = config.SEEDS_DIR / "kb_drafts.json"

RULE_TYPES = {"limit_derogation": ("Derogation from a limit value", "限值豁免")}
ARTICLE_OF_PROVISION = {"5(4)": "a5", "5(5)": "a5pfas"}

_CACHE: dict = {"entries": None}
_LOCK = threading.Lock()


# ---------------------------------------------------------------------------
# Active entries (read by rag.pool_entries and the AI pre-review)
# ---------------------------------------------------------------------------

def invalidate() -> None:
    with _LOCK:
        _CACHE["entries"] = None
    from . import rag
    rag.invalidate_pool()


def as_pool_entry(e: KnowledgeEntry) -> dict:
    return {"id": e.code, "kind": e.kind, "ref": e.ref, "src": "", "source_path": e.source_path or "",
            "page": e.page or 0, "articles": e.articles, "items": e.items, "applies_from": e.applies_from or "",
            "binding": bool(e.binding), "title": e.title, "title_zh": e.title_zh or e.title, "text": e.text or "",
            "text_zh": e.text_zh or e.text or "", "rule": e.rule or {}, "custom": True, "db_id": e.id,
            "added_by": e.created_by, "added_at": e.created_at.strftime("%d %b %Y") if e.created_at else "",
            "update_id": e.update_id}


def _load(session) -> list[dict]:
    return [as_pool_entry(e) for e in
            session.query(KnowledgeEntry).filter_by(status="active").order_by(KnowledgeEntry.id.desc())]


def refresh(session) -> None:
    """Reload from the caller's session, so a change is applied before it is committed (re-run in the same
    transaction). The caller commits right after."""
    rows = _load(session)
    with _LOCK:
        _CACHE["entries"] = rows
    from . import rag
    rag.invalidate_pool()


def active() -> list[dict]:
    with _LOCK:
        if _CACHE["entries"] is not None:
            return _CACHE["entries"]
    try:
        with SessionLocal() as s:
            rows = _load(s)
    except Exception:   # table not created yet — nothing to add, do not cache
        return []
    with _LOCK:
        _CACHE["entries"] = rows
    return rows


def _norm(text: str) -> str:
    return re.sub(r"\s+", " ", (text or "").lower())


def terms_found(terms: list[str], text: str) -> list[str]:
    low = _norm(text)
    return [t for t in terms or [] if t.strip() and _norm(t.strip()) in low]


def scope_text(project, unit) -> str:
    """What the packaging is — matched against the scope of rules in the knowledge base."""
    parts = [project.title, project.product_description or ""]
    units = [unit] if unit else list(project.units)
    for u in units:
        parts += [u.name or "", u.pack_type or ""]
        for c in u.components:
            parts += [c.description or "", c.material or "", c.pack_type or ""]
            if c.supplier_material is not None:
                parts += [c.supplier_material.name or "", c.supplier_material.material or ""]
    return " · ".join(parts)


def scope_for_update(update_id: int) -> list[str] | None:
    """Scope terms of the active rule published with this regulatory update (None = no scoped rule)."""
    for e in active():
        if e.get("update_id") == update_id and (e.get("rule") or {}).get("scope_terms"):
            return e["rule"]["scope_terms"]
    return None


def find_derogation(article: str, scope_text: str) -> dict | None:
    """The active limit derogation whose scope terms occur in the packaging description."""
    for e in active():
        r = e.get("rule") or {}
        if r.get("type") == "limit_derogation" and r.get("article") == article and \
                terms_found(r.get("scope_terms", []), scope_text):
            return e
    return None


def _iso(s) -> dt.date | None:
    try:
        return dt.date.fromisoformat(str(s)) if s else None
    except ValueError:
        return None


def derogation_checks(entry: dict, value: float, scope_text: str, evidence_text: str,
                      limit_desc: str, limit_zh: str) -> list[dict]:
    """The checks that replace an automatic limit failure when a derogation applies."""
    r = entry["rule"]
    ref = entry["ref"] or entry["id"]
    ref_short = re.sub(r"^Commission\s+(Delegated\s+|Implementing\s+)?", "", ref)   # "Decision (EU) 2026/1948"
    today = dt.date.today()
    hit = terms_found(r.get("scope_terms", []), scope_text)
    market = _iso(r.get("market_until"))
    made = _iso(r.get("manufactured_until"))
    lim = r.get("limit_label") or "100 mg/kg"
    out = [{"desc": limit_desc, "desc_zh": limit_zh, "ok": None, "ref": ref,
            "msg": f"{value:g} mg/kg exceeds {lim} — the derogation of {ref_short} may apply to this packaging "
                   f"(matched: {', '.join(hit)}); its conditions must be evidenced",
            "msg_zh": f"{value:g} mg/kg 超过 {lim}——本包装可能适用 {ref_short} 的豁免（匹配：{'、'.join(hit)}）；"
                      f"须证明满足豁免条件"}]
    if market:
        ok = today <= market
        out.append({"desc": f"{ref_short}: placed on the market by {market:%d %b %Y}",
                    "desc_zh": f"{ref_short}：须于 {market:%Y-%m-%d} 前投放市场", "ok": ok, "ref": ref,
                    "msg": f"{(market - today).days} days left" if ok else "Derogation expired — the limit applies",
                    "msg_zh": f"剩余 {(market - today).days} 天" if ok else "豁免已到期——适用限值"})
    if made:
        out.append({"desc": f"{ref_short}: manufactured (melted) by {made:%d %b %Y}",
                    "desc_zh": f"{ref_short}：须于 {made:%Y-%m-%d} 前制造（熔制）", "ok": None, "ref": ref,
                    "msg": "Confirm the melt / production date from the producer's records"
                           + ("" if today <= made else " — production after this date is not covered"),
                    "msg_zh": "请依据生产商记录确认熔制 / 生产日期"
                              + ("" if today <= made else "——此日期后生产的不在豁免范围内")})
    for c in r.get("conditions", []):
        found = terms_found(c.get("terms", []), evidence_text)
        out.append({"desc": f"Condition: {c['en']}", "desc_zh": f"条件：{c.get('zh') or c['en']}",
                    "ok": True if found else None, "ref": c.get("ref") or ref,
                    "msg": f"Evidence mentions: {', '.join(found)}" if found else "Evidence to provide / expert to confirm",
                    "msg_zh": f"证据提及：{'、'.join(found)}" if found else "待提供证据 / 由专家确认"})
    return out


