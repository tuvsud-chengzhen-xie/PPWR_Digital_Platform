MONTHS = {m: i for i, m in enumerate(["january", "february", "march", "april", "may", "june", "july", "august",
                                      "september", "october", "november", "december"], 1)}
_DATE = r"(\d{1,2})\s+(January|February|March|April|May|June|July|August|September|October|November|December)\s+(\d{4})"

# Common condition vocabulary → evidence keywords (EN + ZH) used to recognise supporting evidence.
CONDITION_TERMS = [
    (r"dealkali", ["dealkalis", "dealkaliz", "surface barrier", "脱碱"]),
    (r"permanent(ly)? mark", ["permanent mark", "producer mark", "永久标识", "永久性标识"]),
    (r"free of charge|return(ing|ed)? .*recycl", ["free return", "take-back", "take back", "免费回收", "免费退回"]),
    (r"closed and controlled loop|closed loop", ["closed loop", "closed-loop", "controlled loop", "闭环"]),
    (r"lead-free|transition", ["lead-free", "transition plan", "无铅"]),
    (r"label", ["label"]),
]


def _date_iso(m, i: int = 1) -> str:
    """ISO date from a match of _DATE whose day group is group i."""
    return f"{int(m.group(i + 2)):04d}-{MONTHS[m.group(i + 1).lower()]:02d}-{int(m.group(i)):02d}"


def load_drafts() -> list[dict]:
    try:
        return json.loads(DRAFTS_PATH.read_text(encoding="utf-8"))["drafts"]
    except (OSError, ValueError, KeyError):
        return []


def heuristic_draft(text: str, filename: str = "") -> dict:
    """Extract what the act states about itself — reference, subject, dates, derogation, conditions."""
    flat = re.sub(r"\s+", " ", text or "")
    d: dict = {"origin": "extracted", "kind": "implementing", "binding": True, "ref": "", "title": "",
               "title_zh": "", "text": "", "text_zh": "", "impact": "", "impact_zh": "", "applies_from": "",
               "published": "", "page": 1, "articles": [], "items": [], "rule": {}}
    m = re.search(r"(COMMISSION\s+(DELEGATED|IMPLEMENTING)?\s*(DECISION|REGULATION|DIRECTIVE)\s*\(EU\)\s*(\d{4}/\d+))",
                  flat, re.I)
    if m:
        words = " ".join(w for w in [m.group(2), m.group(3)] if w).title()
        d["ref"] = f"Commission {words} (EU) {m.group(4)}"
        d["kind"] = "regulation" if (m.group(3).lower() == "regulation" and not m.group(2)) else "implementing"
        rest = flat[m.end():]
        sm = re.search(r"of\s+" + _DATE + r"\s+(.*?)\s*(\(Text with EEA relevance\)|THE EUROPEAN COMMISSION)", rest, re.I)
        if sm:
            subject = sm.group(4).strip()
            d["title"] = subject[:1].upper() + subject[1:]
    pm = re.search(r"L series\s+\d{4}/\d+\s+(\d{1,2})\.(\d{1,2})\.(\d{4})", flat) or \
        re.search(r"OJ L,\s*(\d{1,2})\.(\d{1,2})\.(\d{4})", flat)
    if pm:
        pub = dt.date(int(pm.group(3)), int(pm.group(2)), int(pm.group(1)))
        d["published"] = pub.isoformat()
        if re.search(r"enter into force on the day following that of its publication", flat, re.I):
            d["applies_from"] = (pub + dt.timedelta(days=1)).isoformat()
        elif re.search(r"twentieth day following that of its publication", flat, re.I):
            d["applies_from"] = (pub + dt.timedelta(days=20)).isoformat()
    from . import monitor
    d["articles"] = monitor.detect_articles(flat)[:4] or ["core"]
    der = re.search(r"By way of derogation from Article (\d+\(\d+\)) of Regulation \(EU\) 2025/40,\s*(.*?)\s+shall be "
                    r"allowed to exceed (.*?) until " + _DATE + r"(.*?)\.", flat, re.I)
    if der:
        prov = der.group(1)
        art = ARTICLE_OF_PROVISION.get(prov, "a" + prov.split("(")[0])
        subject = der.group(2).strip()
        scope = re.sub(r"\s+packaging$", "", subject, flags=re.I)
        made = re.search(r"may only be manufactured until " + _DATE, flat, re.I)
        conds = []
        tail = flat[der.end():]
        for sent in re.split(r"(?<=\.)\s+(?=\d+\.\s|Article\s+\d)", tail):
            sent = re.sub(r"^((\d+\.\s*)|(Article\s+\w+\s*))+", "", sent.strip()).rstrip("’'.") + "."
            if " shall " not in f" {sent} " or re.search(r"shall apply|enter into force|definitions", sent, re.I):
                continue
            sent = re.split(r"\s+(Article\s+\d+\s|OJ L,|EN OJ L)", sent)[0].strip()
            terms = next((t for rx, t in CONDITION_TERMS if re.search(rx, sent, re.I)), [])
            conds.append({"en": sent[:260], "zh": "", "terms": terms, "ref": ""})
            if len(conds) >= 8:
                break
        d["articles"] = sorted(set(d["articles"]) | {art})
        d["rule"] = {"type": "limit_derogation", "article": art, "provision": f"Art {prov}",
                     "scope_terms": [scope.lower()] if scope else [], "limit_label": "100 mg/kg",
                     "manufactured_until": _date_iso(made) if made else "",
                     "market_until": _date_iso(der, 4), "conditions": conds}
        d["impact"] = (f"AI pre-review: a result above the Art {prov} limit for {subject} is no longer an automatic "
                       f"failure; it is flagged as 'derogation may apply' and the conditions of the act become checks.")
    arts = [d["rule"]["article"]] if d["rule"] else d["articles"]
    d["items"] = [i["id"] for i in catalogue.items() if i["article"] in arts and i["article"] != "core"][:6]
    if der:
        made_txt = f" Manufacture is allowed until {d['rule']['manufactured_until']}." if made else ""
        d["text"] = (der.group(0) + made_txt + " Conditions: " +
                     " ".join(c["en"] for c in d["rule"]["conditions"]))[:1400]
    else:
        ops = re.search(r"HAS ADOPTED THIS (DECISION|REGULATION):(.*)", flat, re.I)
        body = ops.group(2) if ops else flat
        sents = [s.strip() for s in re.split(r"(?<=\.)\s+", body) if re.search(r"derogation|shall|until", s, re.I)]
        d["text"] = (" ".join(sents)[:900]).strip()
    if not d["title"]:
        d["title"] = Path(filename).stem.replace("_", " ")
    return d


def llm_draft(text: str, base: dict) -> dict | None:
    """Optional: let the configured model draft the bilingual summary (grounded in the text only)."""
    if not llm.configured():
        return None
    try:
        out = llm.chat([
            {"role": "system", "content": "You prepare knowledge-base entries on EU packaging law for TÜV SÜD "
             "compliance experts. Use ONLY the text provided; never add dates, limits or conditions that are not "
             "in it. Return JSON with keys title_en, title_zh, summary_en, summary_zh (≤ 140 words each), "
             "impact_en, impact_zh, conditions (list of {en, zh, terms}) where terms are short EN and ZH keywords "
             "that a supporting evidence document would mention."},
            {"role": "user", "content": f"Reference: {base.get('ref')}\n\nText:\n{text[:9000]}"}], max_tokens=1600)
        m = re.search(r"\{.*\}", out, re.S)
        j = json.loads(m.group(0)) if m else {}
    except (llm.LLMError, ValueError):
        return None
    d = dict(base, origin="ai")
    d["title"], d["title_zh"] = j.get("title_en") or base["title"], j.get("title_zh", "")
    d["text"], d["text_zh"] = j.get("summary_en") or base["text"], j.get("summary_zh", "")
    d["impact"], d["impact_zh"] = j.get("impact_en") or base["impact"], j.get("impact_zh", "")
    if base.get("rule") and isinstance(j.get("conditions"), list):
        d["rule"] = dict(base["rule"], conditions=[{"en": c.get("en", ""), "zh": c.get("zh", ""),
                                                    "terms": c.get("terms", []), "ref": ""}
                                                   for c in j["conditions"] if c.get("en")])
    return d


def draft_for(text: str, filename: str = "") -> dict:
    """Curated desk draft for a known act → AI draft (if an LLM is configured) → plain extraction."""
    base = heuristic_draft(text, filename)
    flat = re.sub(r"\s+", " ", text or "")
    for cur in load_drafts():
        if cur.get("match") and cur["match"] in flat:
            return dict(base, **{k: v for k, v in cur.items() if k != "match"}, origin="desk")
    return llm_draft(text, base) or base


def stage_upload(filename: str, content: bytes) -> tuple[str, str]:
    """Keep the uploaded act in data/ until the expert publishes it. Returns (token, extracted text)."""
    STAGING_DIR.mkdir(parents=True, exist_ok=True)
    suffix = Path(filename).suffix.lower() if Path(filename).suffix.lower() in (".pdf", ".html", ".htm") else ".pdf"
    token = uuid.uuid4().hex[:12]
    path = STAGING_DIR / f"{token}{suffix}"
    path.write_bytes(content)
    from . import rag
    return token, "\n".join(rag._pages(path))


def staged_path(token: str) -> Path | None:
    if not re.fullmatch(r"[0-9a-f]{12}", token or ""):
        return None
    hits = list(STAGING_DIR.glob(f"{token}.*")) if STAGING_DIR.exists() else []
    return hits[0] if hits else None


def kb_filename(ref: str, fallback: str) -> str:
    m = re.search(r"(Delegated|Implementing)?\s*(Decision|Regulation|Directive)\s*\(EU\)\s*(\d{4})/(\d+)", ref or "", re.I)
    if m:
        return f"{(m.group(1) or '').title()}{m.group(2).title()}_EU_{m.group(3)}_{m.group(4)}.pdf"
    stem = re.sub(r"[^A-Za-z0-9]+", "_", Path(fallback).stem).strip("_") or "expert_update"
    return f"{stem[:80]}.pdf"


