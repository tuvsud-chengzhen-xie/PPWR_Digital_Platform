"""Manual knowledge-base updates (人工更新知识库) and the AI rules they carry.

An expert uploads a new legal act (e.g. Delegated Decision (EU) 2026/1948 on crystal glass
packaging), reviews a draft knowledge entry, and publishes it. From that moment

* the entry is part of the knowledge pool → the assistant retrieves and cites it (rag.py);
* if it carries a rule, the AI pre-review applies it (ai_review.py) — e.g. a time-bound
  derogation from the Art 5(4) heavy-metal limit turns an automatic "fail" into
  "derogation may apply — verify its conditions";
* every open submission the entry touches is re-reviewed and the verdict change is recorded,
  so the effect of the knowledge update on AI judgement is visible and auditable.

Withdrawing the entry removes it from retrieval and from the rule engine and re-runs the same
submissions — the AI judgement reverts. Nothing here is generated by a model unless an LLM is
configured, and then only as a *draft* the expert must review before publishing.
"""
