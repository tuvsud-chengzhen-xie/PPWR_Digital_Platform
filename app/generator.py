def _new_doc() -> Docx:
    doc = Docx()
    st = doc.styles["Normal"]
    st.font.name = "Calibri"
    st.font.size = Pt(10)
    for name, size in (("Heading 1", 14), ("Heading 2", 12), ("Heading 3", 10.5)):
        h = doc.styles[name]
        h.font.color.rgb = BLUE
        h.font.size = Pt(size)
        h.font.name = "Calibri"
    return doc


def _shade(cell, hex_fill: str) -> None:
    tcpr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_fill)
    tcpr.append(shd)


def _table(doc, headers: list[str], rows: list[list], widths: list[float] | None = None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = ""
        r = c.paragraphs[0].add_run(h)
        r.bold, r.font.size, r.font.color.rgb = True, Pt(8.5), RGBColor(0xFF, 0xFF, 0xFF)
        _shade(c, "003D7A")
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            run = cells[i].paragraphs[0].add_run("" if v is None else str(v))
            run.font.size = Pt(8.5)
            if isinstance(v, str) and v.startswith("OPEN"):
                run.font.color.rgb, run.bold = RED, True
    doc.add_paragraph()
    return t


def _kv(doc, pairs: list[tuple[str, str]]):
    t = doc.add_table(rows=0, cols=2)
    t.style = "Table Grid"
    for k, v in pairs:
        cells = t.add_row().cells
        cells[0].text = ""
        r = cells[0].paragraphs[0].add_run(k)
        r.bold, r.font.size = True, Pt(9)
        _shade(cells[0], "EEF3FA")
        cells[1].text = ""
        run = cells[1].paragraphs[0].add_run(v or "—")
        run.font.size = Pt(9)
        if (v or "").startswith("OPEN"):
            run.font.color.rgb, run.bold = RED, True
    doc.add_paragraph()


def _para(doc, text: str, italic=False, color=None, size=None, bold=False):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.italic, r.bold = italic, bold
    if color is not None:
        r.font.color.rgb = color
    if size:
        r.font.size = Pt(size)
    return p


def _header_footer(doc, left: str, status: str) -> None:
    sec = doc.sections[0]
    hp = sec.header.paragraphs[0]
    hp.text = ""
    r = hp.add_run(f"{left}    ·    {status}")
    r.font.size, r.font.color.rgb = Pt(8), (RED if status.startswith("DRAFT") else GREY)
    fp = sec.footer.paragraphs[0]
    fp.text = ""
    r = fp.add_run(f"Generated by the {config.APP_NAME} ({config.APP_SUB}) on {now():%d %b %Y %H:%M}. "
                   "PPWR (EU) 2025/40 Annex VII Module A.")
    r.font.size, r.font.color.rgb = Pt(7.5), GREY


