class Scope:
    """What one TD covers: a single unit (scenario A) or all units (scenario B)."""

    def __init__(self, project: Project, unit: PackagingUnit | None):
        self.project, self.unit = project, unit
        self.units = [unit] if unit else list(project.units)
        ids = {u.id for u in self.units}
        self.subs = [s for s in project.submissions if s.unit_id in ids or s.unit_id is None]
        self.evidence = [e for e in project.evidence if e.unit_id in ids or e.unit_id is None]
        self.components = [c for u in self.units for c in u.components]
        self.matrix = applicability.matrix(project)

    def sub(self, item_id: str, unit: PackagingUnit | None = None) -> list:
        return [s for s in self.subs if s.item_id == item_id and (unit is None or s.unit_id in (unit.id, None))]

    def field(self, item_id: str, key: str) -> str:
        for s in self.sub(item_id):
            if s.data.get(key):
                return str(s.data[key])
        return ""

    def done(self, item_id: str) -> bool:
        subs = self.sub(item_id)
        return bool(subs) and all(s.is_done for s in subs)

    def ev_for(self, item_ids: list[str]) -> list:
        return [e for e in self.evidence if e.item_id in item_ids]

    @property
    def readiness(self) -> float:
        return workflow.readiness(self.subs)


def _state(s) -> str:
    if s.status == "approved":
        return "Approved" + (f" — {s.reviewed_by}" if s.reviewed_by else "")
    if s.status == "na":
        return "N/A — " + (s.na_reason or "rationale recorded")
    return f"OPEN — {catalogue.STATUS_LABEL[s.status]}"


def _unit_label(s, scope: Scope) -> str:
    if s.unit_id is None:
        return "all units"
    u = next((u for u in scope.units if u.id == s.unit_id), None)
    return u.code if u else ""


def td_number(project: Project, unit: PackagingUnit | None) -> str:
    return f"TD-{project.code}-{unit.code if unit else project.ps_code}"


def doc_number(project: Project, unit: PackagingUnit | None) -> str:
    base = ""
    for s in project.submissions:
        if s.item_id == "C16-66" and s.data.get("docNo"):
            base = s.data["docNo"]
    base = base or f"DoC-{dt.date.today():%Y}-{project.code}"
    return f"{base}-{unit.code}" if unit else base


def _version(session: Session, project: Project, unit, kind: str) -> int:
    q = session.query(Document).filter(Document.project_id == project.id, Document.kind == kind,
                                       Document.unit_id == (unit.id if unit else None))
    return (max((d.version for d in q), default=0)) + 1


