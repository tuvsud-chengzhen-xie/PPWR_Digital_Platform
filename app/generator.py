def build_doc(scope: Scope, number: str, version: int, status: str, td_no: str) -> Docx:
    p, doc = scope.project, _new_doc()
    _header_footer(doc, f"{number} rev {version:02d}", status)
    h = doc.add_heading(f"EU declaration of conformity No {number}", 0)
    h.runs[0].font.color.rgb = BLUE
    _para(doc, "Regulation (EU) 2025/40 — Article 39, Annex VIII model structure", italic=True, color=GREY)
    if status.startswith("DRAFT"):
        _para(doc, "DRAFT — not for signature. The technical documentation still has open items.",
              bold=True, color=RED)
    upis = "; ".join(f"{u.upi or 'OPEN'} ({u.code} {u.name})" for u in scope.units)
    points = [
        ("1. No (unique identification of the packaging)", upis),
        ("2. Name and address of the manufacturer / authorised representative",
         f"{p.client.name}, {p.client.address}" + (f" — authorised representative: {p.client.eu_representative}"
                                                   if p.client.eu_representative else "")),
        ("3.", "This declaration of conformity is issued under the sole responsibility of the manufacturer."),
        ("4. Object of the declaration",
         f"{p.title} — packaging system {p.ps_code}: " + "; ".join(
             f"{u.name}, {u.level.lower()} packaging, {u.pack_type or 'packaging'}, "
             f"{', '.join(sorted({c.material for c in u.components if c.material}))}, SKUs {u.skus or '—'}"
             for u in scope.units)),
        ("5. Conformity with Union harmonisation legislation",
         "The object of the declaration described in point 4 is in conformity with Regulation (EU) 2025/40 "
         "(Articles 5 to 12 as applicable — see technical documentation §5)."
         + (" Regulation (EC) No 1935/2004 (food-contact materials)." if p.food_contact else "")),
        ("6. Harmonised standards / common specifications / other technical specifications",
         "; ".join(r[0] for r in (scope.sub("C14-54")[0].table if scope.sub("C14-54") else []) if r and r[0])
         or "OPEN"),
        ("7. Notified body", "Not applicable — Module A internal production control (Annex VII)."),
        ("8. Additional information",
         f"Technical documentation {td_no}. Retention: "
         + ("10 years (reusable)." if p.reusable else "5 years after placing on the market (single-use).")),
    ]
    _kv(doc, points)
    doc.add_heading("Packaging composition", 2)
    _table(doc, ["Unit", "Component", "Material", "Mass (g)", "Recycled content"],
           [[c.unit.code, c.description or c.pack_type, c.material, f"{c.mass_g:g}" if c.mass_g else "",
             f"{c.recycled_pct:g} %" if c.recycled_pct is not None else "—"] for c in scope.components])
    doc.add_heading("Signed for and on behalf of", 2)
    _kv(doc, [("Manufacturer", p.client.name),
              ("Place and date of issue", f"{scope.field('C16-66', 'place') or 'OPEN'}, {dt.date.today():%d %B %Y}"),
              ("Name, function", scope.field("C16-66", "sign") or "OPEN"),
              ("Signature", "")])
    return doc


def build_package(project: Project, entries: list[tuple[str, str, str]], status: str) -> Docx:
    doc = _new_doc()
    _header_footer(doc, f"Document package {project.code}", status)
    h = doc.add_heading("PPWR document package", 0)
    h.runs[0].font.color.rgb = BLUE
    _para(doc, f"{project.client.name} — {project.title} — packaging system {project.ps_code}", color=GREY)
    doc.add_paragraph("Scenario A: each packaging unit has its own technical documentation and EU declaration of "
                      "conformity. This overview indexes the files handed to the final packaging user.")
    _table(doc, ["Unit", "Technical documentation", "EU declaration of conformity"],
           [[u, td, dc] for u, td, dc in entries])
    return doc


