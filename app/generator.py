def _item_block(doc, scope: Scope, item_ids: list[str]) -> None:
    rows = []
    for iid in item_ids:
        it = catalogue.item(iid)
        for s in scope.sub(iid):
            vals = "; ".join(f"{f['label']}: {s.data.get(f['k'])}" for f in it.get("fields", [])
                             if s.data.get(f["k"]))
            ev = ", ".join(e.code for e in scope.evidence if e.item_id == iid and e.unit_id in (s.unit_id, None))
            rows.append([iid, it["name"], _unit_label(s, scope), vals or "—", ev or "—", _state(s)])
    if rows:
        _table(doc, ["Item", "Requirement", "Unit", "Content", "Evidence", "Status"], rows)


def build_td(scope: Scope, number: str, version: int, status: str) -> Docx:
    p, doc = scope.project, _new_doc()
    _header_footer(doc, f"{number} v{version}", status)
    title = doc.add_heading("Technical Documentation", 0)
    title.runs[0].font.color.rgb = BLUE
    _para(doc, "Regulation (EU) 2025/40 on packaging and packaging waste (PPWR) — Annex VII, "
               "Module A internal production control, point 2", italic=True, color=GREY)
    if status.startswith("DRAFT"):
        _para(doc, f"DRAFT — readiness {scope.readiness:.0%}. Open items are marked OPEN and must be closed "
                   "before this documentation supports an EU declaration of conformity.", bold=True, color=RED)

    doc.add_heading("T00 Cover information", 1)
    _kv(doc, [
        ("TD number / version", f"{number} / v{version}"),
        ("Date", f"{dt.date.today():%d %B %Y}"),
        ("Manufacturer", p.client.name),
        ("Registered address", p.client.address),
        ("EU authorised representative", p.client.eu_representative or "Not applicable"),
        ("Packaged product", p.title),
        ("Packaging system", p.ps_code),
        ("Packaging units covered", ", ".join(f"{u.code} {u.name} (UPI {u.upi or 'OPEN'})" for u in scope.units)),
        ("Technical-file scenario", "A — per-unit technical file (document package)" if p.scenario == "A"
         else "B — consolidated technical file (producer = packaging manufacturer)"),
        ("Retention", "10 years (reusable packaging)" if p.reusable else "5 years after placing on the market (single-use)"),
    ])

    doc.add_heading("T01 Document control", 1)
    _kv(doc, [("Prepared by", scope.field("C16-69", "prep") or "OPEN"),
              ("Reviewed by", scope.field("C16-69", "rev") or "OPEN"),
              ("Approved by", scope.field("C16-69", "appr") or "OPEN"),
              ("Independent review", "TÜV SÜD expert review on the PPWR Digital Platform (item-level audit trail)")])

    doc.add_heading("1 Purpose, scope and regulatory basis", 1)
    doc.add_paragraph(
        f"This technical documentation demonstrates the conformity of the packaging described in section 2 with "
        f"the requirements of Articles 5 to 12 of Regulation (EU) 2025/40 that apply to it, following the "
        f"conformity assessment procedure of Article 38 and Annex VII (Module A). It contains the elements of "
        f"Annex VII point 2 (a)–(f): general description and intended use (§2), design, drawings and component "
        f"materials (§3–§4), standards applied (§16), the qualitative description of the Article 6, 10 and 11 "
        f"assessments (§7, §11, §12), test reports (§17) and an analysis of the risks of non-conformity (§14).")

    doc.add_heading("2 Packaging identification and intended use", 1)
    _table(doc, ["Unit", "UPI", "Name", "Level", "Type", "SKUs", "Mass (g)", "Dimensions (mm)", "Supplier / site"],
           [[u.code, u.upi or "OPEN", u.name, u.level, u.pack_type, u.skus,
             f"{u.mass_g:g}" if u.mass_g else "OPEN", u.dims,
             ", ".join(x for x in (u.supplier_name, u.site, u.country) if x)] for u in scope.units])
    if p.product_description:
        doc.add_paragraph(p.product_description)

    doc.add_heading("3 Packaging structure and BOM", 1)
    _table(doc, ["Component", "Type", "Description", "Structure", "Material", "Mass (g)", "Supplier · trace code", "PCR %"],
           [[c.code, c.pack_type, c.description, c.structure, c.material,
             f"{c.mass_g:g}" if c.mass_g else "OPEN",
             " · ".join(x for x in ((c.supplier.name if c.supplier else ""),
                                    (c.supplier_material.trace_code if c.supplier_material else "")) if x) or "—",
             f"{c.recycled_pct:g}" if c.recycled_pct is not None else "—"] for c in scope.components])
    _item_block(doc, scope, ["C02-07", "C02-08", "C02-09"])

    doc.add_heading("4 Design and manufacturing documentation", 1)
    _item_block(doc, scope, ["C03-10", "C03-11", "C03-12", "C03-13", "C03-14", "C03-15"])

    doc.add_heading("5 PPWR applicability and compliance matrix", 1)
    _table(doc, ["Requirement", "Applicability", "Applies from", "Basis / rationale", "Evidence"],
           [[r.article, r.status, r.applies_from, r.basis, r.evidence] for r in scope.matrix])

    art_sections = [
        ("6 Article 5 — Substances of concern", ["C04-16", "C04-17", "C04-18"]),
        ("7 Article 6 — Recyclability / design for recycling", ["C05-19", "C05-20", "C05-21"]),
        ("8 Article 7 — Recycled content", ["C06-22", "C06-23"]),
        ("9 Article 8 — Biobased feedstock", ["C07-24", "C07-25"]),
        ("10 Article 9 — Compostability", ["C08-26", "C08-27", "C08-28"]),
        ("11 Article 10 — Packaging minimisation", ["C09-29", "C09-30", "C09-31", "C09-32", "C09-33",
                                                    "C09-34", "C09-35", "C09-36"]),
        ("12 Article 11 — Reusability", ["C10-37", "C10-38", "C10-39"]),
        ("13 Article 12 — Labelling", ["C11-40", "C11-41", "C11-42", "C11-43", "C11-44", "C11-45"]),
    ]
    for heading, ids in art_sections:
        doc.add_heading(heading, 1)
        if heading.startswith("6 "):
            rows = []
            for c in scope.components:
                certs = [x for x in (c.supplier_material.certificates if c.supplier_material else [])
                         if x.doc_type == "hm" and x.status == "valid"]
                cert = certs[0] if certs else None
                rows.append([c.code, c.material, cert.number if cert else "—", cert.value if cert else "—",
                             f"{cert.expires:%d %b %Y}" if cert and cert.expires else "—",
                             "≤ 100 mg/kg ✓" if cert and (ai_review._number(cert.value) or 0) <= 100 else
                             ("OPEN — no supplier certificate" if not cert else "EXCEEDS LIMIT")])
            _para(doc, "Heavy metals per component (Art 5(4): Pb + Cd + Hg + Cr(VI) ≤ 100 mg/kg):", bold=True)
            _table(doc, ["Component", "Material", "Report", "Result", "Valid until", "Assessment"], rows)
        _item_block(doc, scope, ids)

    doc.add_heading("14 Risk analysis and assessment of non-conformity", 1)
    risk_rows = []
    for r in scope.matrix:
        if r.status == applicability.NA:
            continue
        open_items = [s for s in scope.subs if catalogue.item(s.item_id)["article"] == r.key and not s.is_done]
        risk_rows.append([r.article, "Low" if not open_items else "Open",
                          r.evidence, "Controlled by approved evidence" if not open_items
                          else f"OPEN — {len(open_items)} item(s) not yet approved"])
    _table(doc, ["Requirement", "Residual risk", "Control / evidence", "Status"], risk_rows)
    _item_block(doc, scope, ["C12-46"])

    doc.add_heading("15 Manufacturing control and change management", 1)
    doc.add_paragraph("Series production remains in conformity through incoming inspection, production "
                      "control and final release (Annex VII point 3; Art 15(4)). Supplier and material changes are "
                      "traced by the platform's change-impact engine, which re-opens affected evidence and flags "
                      "this documentation for update.")
    _item_block(doc, scope, ["C12-47", "C12-48", "C12-49", "C12-50", "C13-51", "C13-52", "C13-53"])

    doc.add_heading("16 Standards and technical specifications", 1)
    std = next((s for s in scope.sub("C14-54")), None)
    rows = [r for r in (std.table if std else []) if r and str(r[0]).strip()]
    _table(doc, ["Standard / specification", "Edition", "Clause", "Requirement covered", "Evidence"],
           rows or [["OPEN — no standards listed", "", "", "", ""]])

    doc.add_heading("17 Evidence register", 1)
    _table(doc, ["Evidence ID", "Title", "Type", "Document no.", "Issuer", "Issued", "Conformity"],
           [[e.code, e.title, catalogue.EVIDENCE_TYPES.get(e.type_code, e.type_code), e.file_no, e.issuer,
             f"{e.issued_date:%d %b %Y}" if e.issued_date else "", e.conformity] for e in scope.evidence]
           or [["OPEN — no evidence uploaded", "", "", "", "", "", ""]])

    doc.add_heading("18 Supplier evidence checklist", 1)
    rows = []
    for c in scope.components:
        m = c.supplier_material
        certs = ", ".join(f"{catalogue.CERT_SHORT[x.doc_type]} {x.number}"
                          + (f" (to {x.expires:%m/%Y})" if x.expires else "")
                          for x in (m.certificates if m else []) if x.status == "valid")
        rows.append([c.code, c.supplier.name if c.supplier else "—", m.code if m else "—",
                     m.trace_code if m else "—", certs or "OPEN — no supplier certificates"])
    _table(doc, ["Component", "Supplier", "Material", "Trace code", "Valid certificates"], rows)
    _item_block(doc, scope, ["C15-56", "C15-57", "C15-58", "C15-59", "C15-60", "C15-61", "C15-62",
                             "C15-63", "C15-64", "C15-65"])

    doc.add_heading("19 Conformity assessment conclusion", 1)
    open_subs = [s for s in scope.subs if not s.is_done]
    if not open_subs:
        doc.add_paragraph("All applicable requirements of Articles 5 to 12 have been assessed and are supported by "
                          "approved evidence. Items not applicable are recorded with their rationale in §5. "
                          "Conformity of the packaging is demonstrated; the EU declaration of conformity may be "
                          "drawn up (Art 39).")
    else:
        _para(doc, f"OPEN — {len(open_subs)} item(s) are not yet approved. Conformity is not yet demonstrated.",
              bold=True, color=RED)
        _table(doc, ["Item", "Requirement", "Unit", "Status"],
               [[s.item_id, catalogue.item(s.item_id)["name"], _unit_label(s, scope),
                 catalogue.STATUS_LABEL[s.status]] for s in open_subs[:60]])

    doc.add_heading("20 EU declaration of conformity — cross-reference", 1)
    _kv(doc, [("EU DoC number", doc_number(p, scope.unit if p.scenario == "A" else None)),
              ("Signatory", scope.field("C16-66", "sign") or "OPEN"),
              ("Place of issue", scope.field("C16-66", "place") or "OPEN")])

    doc.add_heading("21 Approval", 1)
    _kv(doc, [("Prepared", scope.field("C16-69", "prep") or "OPEN"),
              ("Reviewed", scope.field("C16-69", "rev") or "OPEN"),
              ("Approved", scope.field("C16-69", "appr") or "OPEN")])

    doc.add_heading("Appendix A — Evidence file structure", 1)
    _table(doc, ["Folder", "Content"],
           [[f, ", ".join(catalogue.category(c)["name"] for c in cats)] for f, cats in ANNEX_A])
    doc.add_heading("Appendix B — Legal references", 1)
    for ref in ("Regulation (EU) 2025/40 (PPWR), OJ L, 22.1.2025 — Art 5–12, 15, 38, 39, Annex II, IV, VII, VIII",
                "Commission Guidance C(2026) 2151 and PPWR FAQ (2026)",
                "EN 13427–EN 13432 (harmonised standards under Directive 94/62/EC, transitional use)",
                "Regulation (EC) 1935/2004 (food-contact materials), where applicable"):
        doc.add_paragraph(ref, style="List Bullet")
    return doc


