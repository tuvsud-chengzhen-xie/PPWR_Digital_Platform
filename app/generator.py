def _save(doc: Docx, project: Project, name: str) -> Path:
    folder = config.GENERATED_DIR / project.code
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / name
    doc.save(path)
    return path


def generate(session: Session, project: Project, actor: str, trigger: str = "manual") -> list[Document]:
    """Generate the TD/DoC set for the project's scenario. Earlier drafts are superseded."""
    for d in project.documents:
        if d.status == "draft":
            d.status = "superseded"
    made: list[Document] = []
    scopes = [Scope(project, u) for u in project.units] if project.scenario == "A" else [Scope(project, None)]
    entries = []
    for sc in scopes:
        ready = sc.readiness
        status = "ISSUE CANDIDATE" if ready >= 1 else f"DRAFT — {ready:.0%} ready"
        td_no, dc_no = td_number(project, sc.unit), doc_number(project, sc.unit)
        v_td, v_dc = _version(session, project, sc.unit, "TD"), _version(session, project, sc.unit, "DOC")
        stamp = f"{now():%Y%m%d-%H%M%S}"
        td_path = _save(build_td(sc, td_no, v_td, status), project, f"{td_no}_v{v_td}_{stamp}.docx")
        dc_path = _save(build_doc(sc, dc_no, v_dc, status, f"{td_no} v{v_td}"), project,
                        f"{_safe(dc_no)}_rev{v_dc:02d}_{stamp}.docx")
        for kind, number, version, path in (("TD", td_no, v_td, td_path), ("DOC", dc_no, v_dc, dc_path)):
            d = Document(project=project, unit_id=sc.unit.id if sc.unit else None, kind=kind, number=number,
                         version=version, status="draft", path=str(path), readiness=ready, trigger=trigger,
                         generated_by=actor)
            session.add(d)
            made.append(d)
        entries.append((sc.unit.code if sc.unit else "all", f"{td_no} v{v_td}", f"{dc_no} rev {v_dc:02d}"))
    if project.scenario == "A":
        v = _version(session, project, None, "PACKAGE")
        overall = workflow.readiness(project.submissions)
        path = _save(build_package(project, entries, "ISSUE CANDIDATE" if overall >= 1 else "DRAFT"),
                     project, f"PKG-{project.code}_v{v}_{now():%Y%m%d-%H%M%S}.docx")
        d = Document(project=project, unit_id=None, kind="PACKAGE", number=f"PKG-{project.code}", version=v,
                     status="draft", path=str(path), readiness=overall, trigger=trigger, generated_by=actor)
        session.add(d)
        made.append(d)
    return made


def _safe(s: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "_", s)


def dossier_zip(project: Project, documents: list[Document]) -> bytes:
    """Authority-request dossier (Art 15(10): within 10 days) — TD, DoC and every
    evidence file, filed in the Appendix A folder structure."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for d in documents:
            if Path(d.path).exists():
                z.write(d.path, f"{project.code}/00_Document_Control/{Path(d.path).name}")
        for e in project.evidence:
            if not e.stored_path or not Path(e.stored_path).exists():
                continue
            it = catalogue.item(e.item_id) if e.item_id else None
            folder = FOLDER_FOR_CAT.get(it["cat"], "15_Standards_and_Evidence_Register") if it else "17_Supplier_Evidence"
            if e.type_code == "TST":
                folder = "16_Test_Reports"
            z.write(e.stored_path, f"{project.code}/{folder}/{e.code}__{_safe(e.filename or 'file')}")
        z.writestr(f"{project.code}/README.txt",
                   f"PPWR dossier for {project.title} ({project.client.name}).\n"
                   f"Prepared {now():%d %b %Y %H:%M} on the {config.APP_NAME}.\n"
                   "Structure follows Appendix A of the technical documentation.\n")
    return buf.getvalue()
